function result=run_example(outputFile,showFigure)
% RUN_EXAMPLE builds a small synthetic geometry with an island and refinement.
% This example uses synthetic planar coordinates, not a real geographic site.
% Run from this folder: run_example
% Optional: run_example('/path/to/example.slf',false)
base=fileparts(mfilename('fullpath'));
addpath(fileparts(base));
if nargin<1, outputFile=fullfile(base,'example.slf'); end
if nargin<2, showFigure=true; end
region=struct('Bounds',[106200 108200 4001700 4003700], ...
    'Shape','circle','Center',[107200 4002700],'Radius',1000, ...
    'TargetSize',100,'Transition',6000);
cfg=struct('OutlineFile',fullfile(base,'outline.txt'), ...
    'BathymetryFile',fullfile(base,'bathymetry.txt'), ...
    'IslandFile',fullfile(base,'islands.txt'), ...
    'OutputFile',outputFile,'BoundarySpacing',250,'InteriorSpacing',500, ...
    'GridStep',0,'RefinementRegions',region,'ShowFigure',showFigure);
result=telemac_preprocess(cfg);
end
